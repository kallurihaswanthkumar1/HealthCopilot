import React, { useState, useEffect } from 'react';
import {
  Share2,
  Download,
  FileJson,
  FileText,
  ShieldCheck,
  CheckCircle2,
  Copy,
  Eye,
  Lock,
} from 'lucide-react';
import { jsPDF } from 'jspdf';
import { useAuth } from '../context/AuthContext';
import { useLanguage } from '../context/LanguageContext';
import { api } from '../services/api';
import { MedicalDocument } from '../types/health';
import { MedicalDisclaimer } from '../components/MedicalDisclaimer';

export const ExportView: React.FC = () => {
  const { activeProfile } = useAuth();
  const { lang, t } = useLanguage();

  const [loading, setLoading] = useState(false);
  const [documents, setDocuments] = useState<MedicalDocument[]>([]);
  const [summaryData, setSummaryData] = useState<any>(null);
  const [fhirJson, setFhirJson] = useState<string>('');
  const [showFhirPreview, setShowFhirPreview] = useState(false);
  const [copied, setCopied] = useState(false);

  const loadData = async () => {
    if (!activeProfile) return;
    try {
      const [docs, sum] = await Promise.all([
        api.getDocuments(activeProfile.id),
        api.getHealthSummary(activeProfile.id),
      ]);
      setDocuments(docs);
      setSummaryData(sum);

      // Fetch FHIR JSON
      const res = await fetch(api.getFhirExportUrl(activeProfile.id));
      if (res.ok) {
        const bundle = await res.json();
        setFhirJson(JSON.stringify(bundle, null, 2));
      }
    } catch (err) {
      console.error('Error loading export data:', err);
    }
  };

  useEffect(() => {
    loadData();
  }, [activeProfile?.id]);

  const handleDownloadPdf = () => {
    if (!activeProfile) return;
    setLoading(true);

    try {
      const doc = new jsPDF();
      let y = 20;

      // Header
      doc.setFontSize(20);
      doc.setTextColor(13, 148, 136); // Teal color
      doc.text('HealthCopilot - Patient Health Summary', 14, y);
      y += 8;

      doc.setFontSize(10);
      doc.setTextColor(100, 116, 139);
      doc.text(`Generated: ${new Date().toLocaleDateString()} | Confidential Health Record`, 14, y);
      y += 10;

      // Patient Info Box
      doc.setDrawColor(226, 232, 240);
      doc.setFillColor(248, 250, 252);
      doc.roundedRect(14, y, 182, 28, 3, 3, 'FD');

      doc.setFontSize(11);
      doc.setTextColor(15, 23, 42);
      doc.text(`Patient: ${activeProfile.name}`, 18, y + 8);
      doc.text(`Age: ${activeProfile.age} yrs | Gender: ${activeProfile.gender} | Blood: ${activeProfile.bloodGroup}`, 18, y + 16);
      doc.text(`ABHA ID: ${activeProfile.abhaId || '91-4829-1039-4820'} (ABDM Linked)`, 18, y + 24);
      y += 36;

      // Active Medications
      doc.setFontSize(13);
      doc.setTextColor(15, 23, 42);
      doc.text('Current Active Medications', 14, y);
      y += 6;

      doc.setFontSize(9);
      doc.setTextColor(71, 85, 105);
      if (summaryData?.activeMedications && summaryData.activeMedications.length > 0) {
        summaryData.activeMedications.forEach((m: any) => {
          doc.text(`• ${m.name} (${m.dosage}) - ${m.frequency}, ${m.timing}`, 16, y);
          y += 5;
        });
      } else {
        doc.text('No active medications recorded.', 16, y);
        y += 5;
      }
      y += 6;

      // Latest Lab Values
      doc.setFontSize(13);
      doc.setTextColor(15, 23, 42);
      doc.text('Latest Laboratory Parameters', 14, y);
      y += 6;

      doc.setFontSize(9);
      doc.setTextColor(71, 85, 105);
      if (summaryData?.latestLabs && summaryData.latestLabs.length > 0) {
        summaryData.latestLabs.slice(0, 8).forEach((l: any) => {
          doc.text(`• ${l.testName}: ${l.value} ${l.unit} [Range: ${l.referenceRange}] - Status: ${l.status}`, 16, y);
          y += 5;
        });
      } else {
        doc.text('No lab parameters recorded.', 16, y);
        y += 5;
      }
      y += 8;

      // Medical History Timeline Documents
      doc.setFontSize(13);
      doc.setTextColor(15, 23, 42);
      doc.text('Medical Documents on File', 14, y);
      y += 6;

      doc.setFontSize(9);
      doc.setTextColor(71, 85, 105);
      documents.slice(0, 5).forEach((d) => {
        doc.text(`• [${d.date}] ${d.title} (${d.type}) - ${d.doctorName || 'Doctor'}`, 16, y);
        y += 5;
      });
      y += 12;

      // Medical Disclaimer
      doc.setFontSize(8);
      doc.setTextColor(180, 83, 9);
      doc.text('DISCLAIMER: This report is generated by HealthCopilot from patient uploaded documents.', 14, y);
      doc.text('It is for reference and informational purposes only. Consult a licensed physician for diagnosis.', 14, y + 4);

      // Save PDF
      doc.save(`HealthCopilot_${activeProfile.name.replace(/\s+/g, '_')}_Summary.pdf`);
    } catch (err) {
      console.error('PDF error:', err);
      alert('Failed to generate PDF');
    } finally {
      setLoading(false);
    }
  };

  const handleDownloadFhir = () => {
    if (!fhirJson || !activeProfile) return;
    const blob = new Blob([fhirJson], { type: 'application/json' });
    const url = URL.createObjectURL(blob);
    const a = document.createElement('a');
    a.href = url;
    a.download = `ABHA_FHIR_Bundle_${activeProfile.name.replace(/\s+/g, '_')}.json`;
    a.click();
    URL.revokeObjectURL(url);
  };

  const handleCopyFhir = () => {
    navigator.clipboard.writeText(fhirJson);
    setCopied(true);
    setTimeout(() => setCopied(false), 2000);
  };

  return (
    <div className="space-y-6 max-w-4xl mx-auto">
      {/* Top Header */}
      <div>
        <h1 className="text-2xl font-black text-slate-900 tracking-tight flex items-center gap-2">
          <Share2 className="w-6 h-6 text-violet-600" />
          <span>{t('exportAbhaTitle')}</span>
        </h1>
        <p className="text-xs text-slate-500 mt-0.5">
          {t('exportAbhaSubtitle')}
        </p>
      </div>

      <div className="grid grid-cols-1 md:grid-cols-2 gap-6">
        {/* PDF Export Card */}
        <div className="bg-white/85 backdrop-blur-2xl rounded-3xl p-6 sm:p-8 border border-violet-100 shadow-xs flex flex-col justify-between space-y-4">
          <div className="space-y-3">
            <div className="w-12 h-12 rounded-2xl bg-violet-50 text-violet-700 flex items-center justify-center">
              <FileText className="w-6 h-6" />
            </div>
            <div>
              <span className="text-[10px] uppercase font-bold text-violet-700 bg-violet-50 px-2 py-0.5 rounded-full border border-violet-100">
                Download Only • Confidential
              </span>
              <h3 className="text-lg font-bold text-slate-900 mt-1">
                Professional PDF Summary
              </h3>
              <p className="text-xs text-slate-500 leading-relaxed mt-1">
                Generates a clean, doctor-ready 1-page PDF summarizing patient demographics, current active medications, recent abnormal lab findings, and historical timeline.
              </p>
            </div>
          </div>

          <div className="pt-2 border-t border-slate-100 space-y-2">
            <div className="flex items-center gap-1.5 text-[11px] text-slate-500">
              <Lock className="w-3.5 h-3.5 text-emerald-600" />
              <span>Direct client-side download • No public web links created</span>
            </div>
            <button
              onClick={handleDownloadPdf}
              disabled={loading}
              className="w-full py-3 px-4 rounded-xl bg-gradient-to-r from-violet-600 to-indigo-600 hover:from-violet-500 hover:to-indigo-500 text-white font-bold text-xs flex items-center justify-center gap-2 cursor-pointer shadow-md shadow-indigo-600/20 transition-all"
            >
              <Download className="w-4 h-4" />
              <span>{loading ? 'Generating PDF...' : 'Download PDF Health Summary'}</span>
            </button>
          </div>
        </div>

        {/* ABDM / FHIR Export Card */}
        <div className="bg-white rounded-3xl p-6 sm:p-8 border border-slate-200 shadow-xs flex flex-col justify-between space-y-4">
          <div className="space-y-3">
            <div className="w-12 h-12 rounded-2xl bg-indigo-50 text-indigo-700 flex items-center justify-center">
              <FileJson className="w-6 h-6" />
            </div>
            <div>
              <span className="text-[10px] uppercase font-bold text-indigo-700 bg-indigo-50 px-2 py-0.5 rounded-full">
                ABDM / HL7 FHIR R4
              </span>
              <h3 className="text-lg font-bold text-slate-900 mt-1">
                Standard FHIR JSON Bundle
              </h3>
              <p className="text-xs text-slate-500 leading-relaxed mt-1">
                Complies with India’s Ayushman Bharat Digital Mission (ABDM). Packages records into standard Patient, DiagnosticReport, and Observation FHIR resources.
              </p>
            </div>
          </div>

          <div className="pt-2 border-t border-slate-100 space-y-2">
            <div className="flex items-center justify-between">
              <button
                type="button"
                onClick={() => setShowFhirPreview(!showFhirPreview)}
                className="text-xs font-semibold text-indigo-600 hover:text-indigo-800 flex items-center gap-1 cursor-pointer"
              >
                <Eye className="w-3.5 h-3.5" />
                <span>{showFhirPreview ? 'Hide JSON' : 'Inspect FHIR JSON'}</span>
              </button>

              <button
                type="button"
                onClick={handleCopyFhir}
                className="text-xs text-slate-500 hover:text-slate-800 flex items-center gap-1 cursor-pointer"
              >
                <Copy className="w-3.5 h-3.5" />
                <span>{copied ? 'Copied!' : 'Copy'}</span>
              </button>
            </div>

            <button
              onClick={handleDownloadFhir}
              className="w-full py-3 px-4 rounded-xl bg-indigo-600 hover:bg-indigo-700 text-white font-bold text-xs flex items-center justify-center gap-2 cursor-pointer shadow-xs transition-all"
            >
              <Download className="w-4 h-4" />
              <span>Download FHIR JSON</span>
            </button>
          </div>
        </div>
      </div>

      {/* FHIR JSON Inspector */}
      {showFhirPreview && (
        <div className="bg-slate-900 rounded-3xl p-6 text-slate-100 font-mono text-xs space-y-3 shadow-lg animate-in fade-in duration-150">
          <div className="flex items-center justify-between border-b border-slate-800 pb-2">
            <span className="text-teal-400 font-bold">ABDM FHIR R4 Document Bundle:</span>
            <span className="text-[10px] text-slate-400">application/fhir+json</span>
          </div>
          <pre className="max-h-96 overflow-y-auto text-[11px] text-slate-300 leading-relaxed">
            {fhirJson || 'Loading FHIR resources...'}
          </pre>
        </div>
      )}

      <MedicalDisclaimer />
    </div>
  );
};
