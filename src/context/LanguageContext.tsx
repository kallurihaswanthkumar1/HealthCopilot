const LanguageContext = createContext<LanguageContextType>({
  lang: 'te',
  setLang: () => {},
  currentLanguageInfo: SUPPORTED_LANGUAGES[0],
  t: (key) => key,
});

export const LanguageProvider: React.FC<{ children: React.ReactNode }> = ({ children }) => {
  const [lang, setLangState] = useState<IndianLanguage>(() => {
    return (localStorage.getItem('healthcopilot_lang') as IndianLanguage) || 'te';
  });

  const setLang = (newLang: IndianLanguage) => {
    setLangState(newLang);
    localStorage.setItem('healthcopilot_lang', newLang);
  };

  const currentLanguageInfo = SUPPORTED_LANGUAGES.find((l) => l.code === lang) || SUPPORTED_LANGUAGES[0];

  const t = (key: string, variables?: Record<string, string | number>): string => {
    let str = translations[lang]?.[key] || translations['en']?.[key] || key;
    if (variables) {
      for (const [vKey, vVal] of Object.entries(variables)) {
        str = str.replace(new RegExp('\\{' + vKey + '\\}', 'g'), String(vVal));
      }
    }
    return str;
  };

  return (
    <LanguageContext.Provider value={{ lang, setLang, currentLanguageInfo, t }}>
      {children}
    </LanguageContext.Provider>
  );
};

export const useLanguage = () => useContext(LanguageContext);
